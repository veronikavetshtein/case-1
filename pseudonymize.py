def _is_person_token(word: str, prev_word: str = '', is_sentence_start: bool = False) -> tuple[str, str] | None:
    """Проверяет, является ли токен именем собственным, и возвращает (канонический_ключ, базовое_имя)."""
    if not word or len(word) < 3:
        return None
    low = word.lower().replace('ё', 'е')
    if low in NON_PERSON_STOPWORDS:
        return None
    is_cap = word[0].isupper()
    is_unambiguous_typo = any(low.startswith(stem) for stem in UNAMBIGUOUS_LOWER_STEMS)
    if not is_cap and not is_unambiguous_typo and prev_word not in ('>', 'подопечный', 'подопечная', 'подшефный', 'подшефная'):
        return None
    if low in AMBIGUOUS_LOWER:
        # Для омонимичных слов требуем заглавную букву НЕ в начале предложения или явный ролевой контекст
        role_prev = prev_word.lower() in {
            'подопечный', 'подопечная', 'подшефный', 'подшефная', 'воспитанник', 'воспитанница',
            'наставник', 'наставница', 'воспитатель', 'координатор', 'девушка', 'подруга', 'друг', '>'
        }
        if is_sentence_start and not role_prev:
            return None
    return INFLECTION_INDEX.get(low) or INFLECTION_INDEX.get(word.lower())


def pseudonymize_detailed(
    text: str,
    extra_names: list[str] | None = None,
    auto_detect: bool = True,
) -> tuple[str, dict[str, str], list[dict]]:
    """Обратимо заменяет имена, отчества и фамилии лиц на токены [ЛИЦО_N] (или [ЛИЦО_N#k] для падежных форм).

    Гарантирует 100% точное посимвольное восстановление через restore(masked, mapping) == text.
    Возвращает: (masked_text, mapping, entities_summary).
    """
    src = str(text or '')
    if not src.strip():
        return src, {}, []

    # Индекс дополнительных пользовательских имён/обозначений (включая их падежные формы)
    custom_index: dict[str, tuple[str, str]] = {}
    explicit_phrases: list[tuple[str, str]] = []
    if extra_names:
        for raw_name in extra_names:
            clean = str(raw_name).strip()
            if not clean:
                continue
            low = clean.lower()
            canon = CANONICAL_EQUIVALENTS.get(low, clean)
            if ' ' in clean:
                explicit_phrases.append((clean, canon))
            else:
                for form in generate_name_forms(clean):
                    custom_index[form] = (canon, clean)
                    custom_index[form.replace('ё', 'е')] = (canon, clean)

    # Находим спаны имён (Имя + [Отчество] + [Фамилия])
    spans: list[tuple[int, int, str, str, str]] = []  # (start, end, surface, canon_key, display_name)

    # 1. Сначала ищем многословные явные фразы, если заданы
    occupied: list[tuple[int, int]] = []
    for phrase, canon in sorted(explicit_phrases, key=lambda x: len(x[0]), reverse=True):
        for m in re.finditer(r'(?<!\w)' + re.escape(phrase) + r'(?!\w)', src, flags=re.I):
            s, e = m.span()
            if any( not (e <= os or s >= oe) for os, oe in occupied ):
                continue
            occupied.append((s, e))
            spans.append((s, e, m.group(0), canon, phrase))

    # 2. Токенизируем текст с сохранением позиций
    tokens = [(m.group(0), m.start(), m.end()) for m in re.finditer(r'[А-Яа-яЁёA-Za-z0-9>]+', src)]
    i = 0
    while i < len(tokens):
        word, s, e = tokens[i]
        if any(not (e <= os or s >= oe) for os, oe in occupied):
            i += 1
            continue

        prev_word = tokens[i - 1][0] if i > 0 else ''
        # Проверяем, находится ли слово в начале предложения
        between_prev = src[tokens[i - 1][2]:s] if i > 0 else ''
        is_sent_start = (i == 0) or bool(re.search(r'[.!?…\n]', between_prev))

        low = word.lower().replace('ё', 'е')
        matched_info = custom_index.get(low) or custom_index.get(word.lower())
        if matched_info is None and auto_detect:
            matched_info = _is_person_token(word, prev_word=prev_word, is_sentence_start=is_sent_start)

        if matched_info is not None:
            canon_key, display_name = matched_info
            end_pos = e
            next_idx = i + 1
            # Проверяем, следует ли сразу за именем Отчество и/или Фамилия через пробел
            while next_idx < len(tokens):
                nxt_word, ns, ne = tokens[next_idx]
                gap = src[end_pos:ns]
                if gap not in (' ', '  '):
                    break
                if nxt_word.lower().replace('ё', 'е') in NON_PERSON_STOPWORDS:
                    break
                if PATRONYMIC_RE.match(nxt_word) or SURNAME_RE.match(nxt_word):
                    end_pos = ne
                    next_idx += 1
                else:
                    break
            surface = src[s:end_pos]
            occupied.append((s, end_pos))
            spans.append((s, end_pos, surface, canon_key, display_name))
            i = next_idx
            continue

        i += 1

    if not spans:
        return src, {}, []

    spans.sort(key=lambda x: x[0])

    # Группируем по каноническому лицу в порядке первого появления в тексте
    person_order: dict[str, int] = {}
    person_surfaces: dict[int, dict[str, str]] = {}  # person_num -> {surface_string: token_str}
    person_meta: dict[int, dict] = {}
    mapping: dict[str, str] = {}

    out_parts: list[str] = []
    cursor = 0
    for s, e, surface, canon_key, display_name in spans:
        out_parts.append(src[cursor:s])
        if canon_key not in person_order:
            p_num = len(person_order) + 1
            person_order[canon_key] = p_num
            person_surfaces[p_num] = {}
            person_meta[p_num] = {
                'person_id': f'ЛИЦО_{p_num}',
                'canonical_name': canon_key,
                'forms': [],
                'count': 0,
            }
        p_num = person_order[canon_key]
        surf_map = person_surfaces[p_num]
        if surface not in surf_map:
            idx = len(surf_map) + 1
            token = f'[ЛИЦО_{p_num}]' if idx == 1 else f'[ЛИЦО_{p_num}#{idx}]'
            surf_map[surface] = token
            mapping[token] = surface
        else:
            token = surf_map[surface]

        meta = person_meta[p_num]
        meta['count'] += 1
        if surface not in meta['forms']:
            meta['forms'].append(surface)

        out_parts.append(token)
        cursor = e

    out_parts.append(src[cursor:])
    masked_text = ''.join(out_parts)
    entities_summary = list(person_meta.values())
    return masked_text, mapping, entities_summary


def replace_explicit(text, names):
    """Заменяет явно перечисленные имена (а при пустом списке — автоматически распознаёт имена в тексте),
    сохраняя обратную совместимость кортежа (masked, mapping)."""
    clean_names = [str(x).strip() for x in (names or []) if str(x).strip()]
    if not clean_names:
        # Если явный список пуст, возвращаем без изменений для строгой совместимости со старыми вызовами
        return str(text), {}
    masked, mapping, _ = pseudonymize_detailed(str(text), extra_names=clean_names, auto_detect=False)
    return masked, mapping


def auto_pseudonymize(text, extra_names=None):
    """Автоматическая псевдонимизация всех имён, отчеств, фамилий и падежных форм в тексте."""
    masked, mapping, _ = pseudonymize_detailed(str(text), extra_names=extra_names, auto_detect=True)
    return masked, mapping


def restore(masked, mapping):
    """Точное посимвольное обратное восстановление исходного текста по таблице соответствий."""
    out = str(masked)
    if not mapping:
        return out
    # Сортируем ключи по убыванию длины, чтобы [ЛИЦО_1#2] и [ЛИЦО_10] не конфликтовали с [ЛИЦО_1]
    for placeholder in sorted(mapping.keys(), key=len, reverse=True):
        out = out.replace(placeholder, str(mapping[placeholder]))
    return out


def save_private_map(mapping, path=DEFAULT_VAULT, secret_key=''):
    """Сохраняет таблицу соответствий в локальный защищённый файл (вне публичного экспорта)."""
    target = Path(path)
    payload_str = json.dumps(mapping, ensure_ascii=False, indent=2)
    if secret_key:
        key_bytes = hashlib.sha256(secret_key.encode('utf-8')).digest()
        raw_bytes = payload_str.encode('utf-8')
        xored = bytes(b ^ key_bytes[i % len(key_bytes)] for i, b in enumerate(raw_bytes))
        envelope = {
            'protected': True,
            'cipher': 'sha256-xor-base64',
            'data': base64.b64encode(xored).decode('ascii'),
        }
        target.write_text(json.dumps(envelope, ensure_ascii=False, indent=2), encoding='utf-8')
    else:
        target.write_text(payload_str, encoding='utf-8')


def load_private_map(path=DEFAULT_VAULT, secret_key=''):
    """Загружает таблицу соответствий из локального хранилища."""
    target = Path(path)
    if not target.exists():
        return {}
    loaded = json.loads(target.read_text(encoding='utf-8'))
    if isinstance(loaded, dict) and loaded.get('protected') is True:
        if not secret_key:
            raise ValueError('Хранилище псевдонимов защищено ключом. Укажите ключ доступа.')
        key_bytes = hashlib.sha256(secret_key.encode('utf-8')).digest()
        xored = base64.b64decode(loaded['data'].encode('ascii'))
        raw_bytes = bytes(b ^ key_bytes[i % len(key_bytes)] for i, b in enumerate(xored))
        return json.loads(raw_bytes.decode('utf-8'))
    return loaded
