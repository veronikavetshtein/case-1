def generate_name_forms(nom: str) -> set[str]:
    """Генерирует все основные русские падежные формы имени (И.п., Р.п., Д.п., В.п., Т.п., П.п.)."""
    w = nom.strip().lower()
    if not w:
        return set()
    forms = {w}
    # Неизменяемые краткие формы (Крис, Анис — Анис склоняется, Крис — нет)
    if w == 'крис':
        return {'крис'}
    if w.endswith('ия'):
        stem = w[:-2]
        forms.update({stem + 'ия', stem + 'ии', stem + 'ию', stem + 'ией', stem + 'иею'})
    elif w.endswith('ья'):
        stem = w[:-2]
        forms.update({stem + 'ья', stem + 'ьи', stem + 'ье', stem + 'ью', stem + 'ьей', stem + 'ьею'})
    elif w.endswith('я'):
        stem = w[:-1]
        forms.update({stem + 'я', stem + 'и', stem + 'е', stem + 'ю', stem + 'ей', stem + 'ею'})
    elif w.endswith('а'):
        stem = w[:-1]
        # После г, к, х, ж, ш, щ, ч в Р.п. пишется -и, в Т.п. после ж, ш, щ, ч без ударения -ей
        gen = stem + ('и' if stem[-1:] in 'гкхжшщч' else 'ы')
        forms.update({stem + 'а', gen, stem + 'е', stem + 'у', stem + 'ой', stem + 'ей', stem + 'ою', stem + 'ею'})
    elif w.endswith('й'):
        stem = w[:-1]
        forms.update({stem + 'й', stem + 'я', stem + 'ю', stem + 'ем', stem + 'ём', stem + 'е', stem + 'и'})
    elif w.endswith('ь'):
        stem = w[:-1]
        # Мужские (Игорь) и женские (Любовь)
        forms.update({stem + 'ь', stem + 'я', stem + 'ю', stem + 'ем', stem + 'ём', stem + 'е', stem + 'и', stem + 'ью'})
    elif w == 'павел':
        forms.update({'павел', 'павла', 'павлу', 'павлом', 'павле'})
    elif w in ('лев', 'пётр', 'петр'):
        if w == 'лев':
            forms.update({'лев', 'льва', 'льву', 'львом', 'льве'})
        else:
            forms.update({'пётр', 'петр', 'петра', 'петру', 'петром', 'петре'})
    else:
        # Согласная на конце (Максим, Иван, Герман, Анис, Марк, Степан, Богдан, Кирилл, Влад)
        forms.update({w, w + 'а', w + 'у', w + 'ом', w + 'ем', w + 'е'})
    return forms


def _build_inflection_index() -> dict[str, tuple[str, str]]:
    """Возвращает словарь: словоформа_в_нижнем_регистре -> (каноническая_группа, отображаемое_имя)."""
    index: dict[str, tuple[str, str]] = {}
    for base_lower, display in KNOWN_NAMES.items():
        canon = CANONICAL_EQUIVALENTS.get(base_lower, display)
        for form in generate_name_forms(base_lower):
            if form not in index:
                index[form] = (canon, display)
            # Также поддерживаем замену ё -> е
            form_e = form.replace('ё', 'е')
            if form_e not in index:
                index[form_e] = (canon, display)
    return index


INFLECTION_INDEX = _build_inflection_index()

